-- forum_media: image metadata; object bytes live in S3/MinIO
-- media-service connects with currentSchema=forum_media
SET search_path TO forum_media;

CREATE TABLE IF NOT EXISTS db_image_store (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid          integer NOT NULL,
    name         varchar(255) NOT NULL,
    content_type varchar(64),
    size         bigint,
    time         timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at   timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_image_name UNIQUE (name)
);

CREATE INDEX IF NOT EXISTS idx_image_uid_time ON db_image_store (uid, time);

COMMENT ON COLUMN db_image_store.name IS 'object name, e.g. /avatar/<uuid> or /cache/<yyyyMMdd>/<uuid>';
