-- forum_content: topic types, topics, comments, interactions, profile snapshot
-- content-service connects with currentSchema=forum_content
SET search_path TO forum_content;

CREATE TABLE IF NOT EXISTS db_topic_type (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   varchar(255),
    "desc" varchar(255),
    color  varchar(255)
);

CREATE TABLE IF NOT EXISTS db_topic (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title   varchar(255),
    content text,
    uid     integer,
    type    integer,
    time    timestamp,
    top     smallint NOT NULL DEFAULT 0 CHECK (top IN (0, 1))
);

CREATE INDEX IF NOT EXISTS idx_topic_type_time ON db_topic (type, time);
CREATE INDEX IF NOT EXISTS idx_topic_uid ON db_topic (uid);
CREATE INDEX IF NOT EXISTS idx_topic_top_time ON db_topic (top, time);

CREATE TABLE IF NOT EXISTS db_topic_comment (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid     integer,
    tid     integer,
    content text,
    time    timestamp,
    quote   integer
);

CREATE INDEX IF NOT EXISTS idx_comment_tid_time ON db_topic_comment (tid, time);
CREATE INDEX IF NOT EXISTS idx_comment_uid ON db_topic_comment (uid);

CREATE TABLE IF NOT EXISTS db_topic_interact_like (
    tid  integer NOT NULL,
    uid  integer NOT NULL,
    time timestamp,
    PRIMARY KEY (tid, uid)
);

CREATE INDEX IF NOT EXISTS idx_like_uid ON db_topic_interact_like (uid);
CREATE INDEX IF NOT EXISTS idx_like_tid_time ON db_topic_interact_like (tid, time);

CREATE TABLE IF NOT EXISTS db_topic_interact_collect (
    tid  integer NOT NULL,
    uid  integer NOT NULL,
    time timestamp,
    PRIMARY KEY (tid, uid)
);

CREATE INDEX IF NOT EXISTS idx_collect_uid ON db_topic_interact_collect (uid);
CREATE INDEX IF NOT EXISTS idx_collect_tid_time ON db_topic_interact_collect (tid, time);

-- 轻量展示快照；不复制手机号/邮箱等 PII。当前 content-service 以 Feign 为主，保留表用于后续优化。
CREATE TABLE IF NOT EXISTS db_user_snapshot (
    uid          integer PRIMARY KEY,
    username     varchar(64),
    avatar       varchar(255),
    gender       smallint,
    show_gender  smallint NOT NULL DEFAULT 1,
    updated_at   timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_snapshot_username ON db_user_snapshot (username);

COMMENT ON COLUMN db_topic_type."desc" IS 'topic type description; quoted because desc is a SQL keyword';
COMMENT ON COLUMN db_topic.top IS '1 = pinned, 0 = normal';
