-- forum_notification: in-app notification and event idempotency
-- notification-service connects with currentSchema=forum_notification
SET search_path TO forum_notification;

CREATE TABLE IF NOT EXISTS db_notification (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid      integer NOT NULL,
    title    varchar(255),
    content  varchar(512),
    type     varchar(64),
    url      varchar(255),
    time     timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    event_id varchar(64),
    read_at  timestamp,
    CONSTRAINT uk_notification_event UNIQUE (event_id)
);

CREATE INDEX IF NOT EXISTS idx_notification_uid_time ON db_notification (uid, time);
CREATE INDEX IF NOT EXISTS idx_notification_uid_read ON db_notification (uid, read_at);

COMMENT ON COLUMN db_notification.event_id IS 'idempotency key from RabbitMQ notification event';
COMMENT ON COLUMN db_notification.read_at IS 'reserved for read/unread semantics';
