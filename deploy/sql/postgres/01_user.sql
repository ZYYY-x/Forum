-- forum_user: account, profile, privacy
-- user-service connects with currentSchema=forum_user
SET search_path TO forum_user;

CREATE TABLE IF NOT EXISTS db_account_jwt (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      varchar(255),
    password      varchar(255),
    email         varchar(255),
    role          varchar(255),
    avatar        varchar(255),
    register_time timestamp,
    CONSTRAINT uk_account_username UNIQUE (username),
    CONSTRAINT uk_account_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS db_account_details (
    id      integer PRIMARY KEY,
    gender  smallint NOT NULL DEFAULT 0,
    phone   varchar(255),
    qq      varchar(255),
    wx      varchar(255),
    "desc"  varchar(255),
    CONSTRAINT fk_details_account
        FOREIGN KEY (id) REFERENCES db_account_jwt (id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS db_account_privacy (
    id      integer PRIMARY KEY,
    phone   boolean NOT NULL DEFAULT true,
    email   boolean NOT NULL DEFAULT true,
    wx      boolean NOT NULL DEFAULT true,
    qq      boolean NOT NULL DEFAULT true,
    gender  boolean NOT NULL DEFAULT true,
    CONSTRAINT fk_privacy_account
        FOREIGN KEY (id) REFERENCES db_account_jwt (id)
        ON DELETE CASCADE
);

COMMENT ON COLUMN db_account_details."desc" IS 'profile description; quoted because desc is a SQL keyword';
